alter = 30
name = "Lara" 

print(name + " is " + str(alter) + " years old.")

alter2 = 30
name2 = "Aurelius"

print(f"{name2} is {alter2} years old.")


# Merke: Das f vor dem String macht ihn zu einem f-String.
# In {geschweiften Klammern} kannst du Variablen direkt einsetzen,
# ohne sie mit + zu verketten und ohne str() für Zahlen zu benutzen.