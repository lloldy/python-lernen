# Notiz: print() gibt einen Wert auf der Konsole aus.
print(1)

# Notiz: Python rechnet direkt mit Zahlen, z.B. Addition.
print(5 + 1)

# Notiz: type() zeigt den Datentyp eines Werts an.
# "j" steht in Python fuer den Imaginaerteil einer komplexen Zahl,
# darum braucht es eine Zahl davor, z.B. 1j (nicht nur "j").
print(type(5 + 1j))

# Notiz: Subtraktion
print(5 - 2)

# Notiz: Multiplikation
print(4 * 3)

# Notiz: Division ergibt in Python immer eine Kommazahl (float)
print(7 / 2)

# Notiz: Ganzzahlige Division - schneidet den Rest einfach ab
print(7 // 2)

# Notiz: Modulo - gibt den Rest einer Division zurueck
print(7 % 2)

# Notiz: Potenzrechnen (hoch)
print(2 ** 3)

# Notiz: type() bei einer ganzen Zahl -> int
print(type(5))

# Notiz: type() bei einer Kommazahl -> float
print(type(5.0))

# Notiz: Umwandeln (Casten) von int zu float
print(float(5))

# Notiz: Umwandeln von float zu int, Nachkommastellen fallen einfach weg
print(int(5.9))
